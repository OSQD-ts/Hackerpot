/**
 * The OSQD UI kit's stylesheet, as the string the dashboard stamps into its one nonced
 * <style> and the embedded element adopts into its shadow root.
 *
 * The look of both dashboards comes from `@osqd/ui`, a devDependency like `@osqd/jql`: it is
 * read from node_modules here, minified, and committed as a generated module, so the package
 * keeps zero runtime dependencies and the page keeps its CSP — one nonced style, nothing
 * fetched. Only the parts a dashboard uses are taken (tokens, base, components, charts, data);
 * forms and layout would be dead weight in every response, since the page is sent `no-store`.
 *
 * `npm run client:check` fails when the committed copy no longer matches the installed kit,
 * which is what an upgrade of `@osqd/ui` without a rebuild looks like.
 */
import { transform } from "esbuild";
import { readFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const PARTS = ["tokens.css", "base.css", "components.css", "charts.css", "data.css"];

/**
 * What must never reach the page from a stylesheet: the end of the <style> element, an HTML
 * comment opener the parser reads first, and anything fetched — `default-src 'none'` would
 * refuse it anyway, and a refused font is a page that renders differently than it was tested.
 */
const FORBIDDEN = ["</style", "<!--", "-->", "@import", "url(http", "url(//"];

export async function buildUiCss(root) {
  const require = createRequire(join(root, "package.json"));
  const manifest = require.resolve("@osqd/ui/package.json");
  const kit = dirname(manifest);
  const { version } = JSON.parse(await readFile(manifest, "utf8"));
  const source = (await Promise.all(PARTS.map((part) => readFile(join(kit, "styles", part), "utf8")))).join("\n");
  const { code } = await transform(source, { loader: "css", minify: true, legalComments: "none", charset: "utf8" });
  for (const sequence of FORBIDDEN) {
    if (code.includes(sequence)) throw new Error(`@osqd/ui ${version} styles contain ${JSON.stringify(sequence)}, which the dashboard page cannot carry.`);
  }
  return `/**
 * Generated by \`npm run client:build\` from @osqd/ui ${version} (${PARTS.join(", ")}). Do not edit.
 *
 * The UI kit's stylesheet, stamped ahead of the dashboard's own rules. See scripts/build-ui-css.mjs.
 */

/* eslint-disable */
export const UI_KIT_VERSION = ${JSON.stringify(version)};
export const UI_CSS = ${JSON.stringify(code)};
`;
}
